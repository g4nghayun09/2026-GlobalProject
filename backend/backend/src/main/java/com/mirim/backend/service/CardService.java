    public List<Card> getCardList() {
        return cards;
    }

    public List<Card> getCardsByCategory(String keyword) {
        List<Card> cardList = new ArrayList<>();
        for (Card card : cards) {
            if (card.getCategory().equals(keyword)) {
                cardList.add(card);
            }
        }

        if (cardList.isEmpty()) {
            return null;
        }
        return cardList;
    }

    public List<Card> getCardsByKeyword(String keyword) {
        List<Card> cardList = new ArrayList<>();
        for (Card card : cards) {
            if (card.getTitle().equals(keyword)) {
                cardList.add(card);
            }
        }

        if (cardList.isEmpty()) {
            return null;
        }
        return cardList;
    }

    public Card getCardById(Integer id) {
        Card card;
        try {
            card = cards.get((int) (id - 1));
        } catch (IndexOutOfBoundsException e) {
            return null;
        }
        return card;
    }
